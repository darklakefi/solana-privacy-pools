/// Verify a withdrawal proof using Groth16
pub fn verify_withdraw_proof(proof_data: &WithdrawProofData) -> bool {
    // The withdraw circuit has 8 public inputs:
    // 0: withdrawnValue
    // 1: stateRoot
    // 2: stateTreeDepth
    // 3: ASPRoot
    // 4: ASPTreeDepth
    // 5: context
    // 6: newCommitmentHash
    // 7: existingNullifierHash
    
    const NR_PUBLIC_INPUTS: usize = 8;
    
    if proof_data.public_signals.len() != NR_PUBLIC_INPUTS {
        return false;
    }
    
    // Convert Vec to fixed-size array
    let public_signals: [[u8; 32]; NR_PUBLIC_INPUTS] = match proof_data.public_signals[..].try_into() {
        Ok(arr) => arr,
        Err(_) => return false,
    };
    
    // Create verifying key
    let vk = Groth16Verifyingkey {
        nr_pubinputs: NR_PUBLIC_INPUTS,
        vk_alpha_g1: WITHDRAW_VK_ALPHA_G1,
        vk_beta_g2: WITHDRAW_VK_BETA_G2,
        vk_gamme_g2: WITHDRAW_VK_GAMMA_G2,
        vk_delta_g2: WITHDRAW_VK_DELTA_G2,
        vk_ic: &WITHDRAW_VK_IC,
    };
    
    // Create and run verifier
    match Groth16Verifier::<NR_PUBLIC_INPUTS>::new(
        &proof_data.proof_a,
        &proof_data.proof_b,
        &proof_data.proof_c,
        &public_signals,
        &vk,
    ) {
        Ok(mut verifier) => {
            // Verify the proof without field check (we know our values are valid)
            verifier.verify_unchecked().is_ok()
        }
        Err(_) => false,
    }
}

